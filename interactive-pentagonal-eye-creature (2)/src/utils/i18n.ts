let EN2RU: Record<string, string> | null = null;
function buildEn2Ru() {
  if (!EN2RU) {
    EN2RU = { ...EXTRA_EN2RU };
    for (const k of Object.keys(UI_RU)) {
      const en = UI_EN[k] ?? k;
      if (en && !EN2RU[en]) EN2RU[en] = UI_RU[k];
    }
  }
  return EN2RU;
}

/** Переводит готовую английскую строку интерфейса в текущий язык */
export function tl(text: string): string {
  if (current === 'en' || !text) return text;
  return buildEn2Ru()[text] ?? text;
}
