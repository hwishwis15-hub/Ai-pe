export function t(key: string): string {
  const dict = current === 'ru' ? UI_RU : UI_EN;
  return dict[key] ?? UI_EN[key] ?? key;
}

/** Переводит динамические английские фразы (настроения, действия, игры).
 *  Сначала ищет точное совпадение, затем пытается перевести части
 *  составных строк («A & B — label», «X: label», «X — label»). */
export function tp(text: string): string {
  if (current === 'en' || !text) return text;

  // 1) точное совпадение
  const direct = PHRASE_RU[text];
  if (direct) return direct;

  // 2) «X & Y — label» (социальные игры)
  const amp = text.match(/^(.+?)\s*&\s*(.+?)\s*—\s*(.+)$/);
  if (amp) return `${amp[1]} и ${amp[2]} — ${tp(amp[3])}`;

  // 3) «X — label»
  const dash = text.match(/^(.+?)\s*—\s*(.+)$/);
  if (dash && PHRASE_RU[dash[2]]) return `${dash[1]} — ${PHRASE_RU[dash[2]]}`;

  // 4) «X: label»
  const colon = text.match(/^(.+?):\s*(.+)$/);
  if (colon && PHRASE_RU[colon[2]]) return `${colon[1]}: ${PHRASE_RU[colon[2]]}`;

  // 5) частицы внутри («X is eating!», «X wants revenge»…)
  const partial = Object.keys(PHRASE_RU).find((k) => text.includes(k));
  if (partial) return text.replace(partial, PHRASE_RU[partial]);

  return text;
}

